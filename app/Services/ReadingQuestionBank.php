    /**
     * Lấy danh sách câu hỏi theo Part hoặc tất cả
     */
    public static function getQuestions(?int $part = null): array
    {
        $all = array_merge(
            self::getPart5Questions(),
            self::getPart6Questions(),
            self::getPart7Questions()
        );

        if ($part === null) {
            return $all;
        }

        return array_values(array_filter($all, function ($q) use ($part) {
            return ($q['part_number'] ?? null) === $part;
        }));
    }

